create table products(id bigint generated always as identity primary key,title text,price int,cost int default 0,category text,images text[],sizes text,colors text,descr text,active bool default true,created_at timestamptz default now());
create table orders(id bigint generated always as identity primary key,name text,phone text,address text,city text,items jsonb,total int,status text default 'New',created_at timestamptz default now());
alter table products enable row level security;
alter table orders enable row level security;
create policy "r" on products for select using (true);
create policy "a" on products for all to authenticated using (true) with check (true);
create policy "o" on orders for insert to anon,authenticated with check (true);
create policy "oa" on orders for all to authenticated using (true) with check (true);
insert into storage.buckets(id,name,public) values('pics','pics',true);
create policy "pr" on storage.objects for select using (bucket_id='pics');
create policy "pw" on storage.objects for all to authenticated using (bucket_id='pics') with check (bucket_id='pics');
